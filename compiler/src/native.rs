    #[test]
    fn makes_file_scope_state_thread_local_in_workers() {
        let source = "static u8* porf_mem;\nstatic u32 counts[64] = {0};\nstatic const char text[] = \"{ static int no; }\";\n\
            static int helper(int a) {\n  static int calls = 0;\n  return a + calls;\n}\n/* a { comment\nstatic int inside_comment;\n*/\n\
            /* reactc:shared-begin */\nstatic int shared_lock;\n/* reactc:shared-end */\nstatic jsval after;\n";
        let converted = thread_local_statics(source);
        assert!(converted.contains("static __thread u8* porf_mem;"));
        assert!(converted.contains("static __thread u32 counts[64] = {0};"));
        assert!(converted.contains("static const char text[]"));
        assert!(converted.contains("static int helper(int a) {"));
        assert!(converted.contains("  static int calls = 0;"));
        assert!(converted.contains("\nstatic int inside_comment;"));
        assert!(converted.contains("\nstatic int shared_lock;"));
        assert!(converted.contains("static __thread jsval after;"));
    }

